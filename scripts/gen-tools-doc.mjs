// Generates docs/tools.md from the MCP tool definitions in server/agent.js, so the reference never drifts.
//   npm run docs:tools        (CI fails if the committed file is out of date: npm run docs:check)
import { writeFileSync, readFileSync } from 'node:fs';
import { TOOLS } from '../server/agent.js';

const who = (s) => String(s ?? '').replace(/^\{user\}/, 'The user').replaceAll('{user}', 'the user');
const esc = (s) => String(s ?? '').replaceAll('|', '\\|').replaceAll('\n', ' ');
const typeOf = (p) => {
  if (!p) return '';
  if (p.enum) return p.enum.filter((x) => x !== null && x !== '').map((x) => `\`${x}\``).join(' · ') || 'enum';
  if (p.type === 'array') return `array of ${p.items?.type === 'object' ? 'objects' : p.items?.type || 'values'}`;
  return Array.isArray(p.type) ? p.type.join(' / ') : p.type || 'object';
};
const out = [
  '# MCP tools reference',
  '',
  '<!-- Generated by scripts/gen-tools-doc.mjs from server/agent.js — do not edit by hand. -->',
  '',
  'The board serves these tools at `POST /mcp` (MCP Streamable HTTP, stateless JSON-RPC 2.0). Every answer is short',
  'Hebrew text meant to be read by the agent; dates and times are resolved by the server. Each agent sees only its',
  'person\'s spaces. In the descriptions, "the user" is replaced with the person\'s name for each agent.',
  '',
  '| Tool | What it is for |',
  '| --- | --- |',
  ...TOOLS.map((t) => `| [\`${t.name}\`](#${t.name.replaceAll('_', '-')}) | ${esc(who(t.description.split(/(?<=\.)\s/)[0]))} |`),
  '',
];
for (const t of TOOLS) {
  out.push(`## \`${t.name}\``, '', who(t.description), '');
  const props = Object.entries(t.inputSchema?.properties || {});
  if (!props.length) { out.push('_No parameters._', ''); continue; }
  const req = new Set(t.inputSchema.required || []);
  out.push('| Parameter | Type | Required | Description |', '| --- | --- | --- | --- |');
  for (const [name, p] of props) {
    out.push(`| \`${name}\` | ${esc(typeOf(p))} | ${req.has(name) ? 'yes' : ''} | ${esc(who(p.description))} |`);
    const sub = p.type === 'array' && p.items?.type === 'object' ? p.items.properties : null;
    if (sub) for (const [sn, sp] of Object.entries(sub)) out.push(`| &nbsp;&nbsp;↳ \`${sn}\` | ${esc(typeOf(sp))} | ${(p.items.required || []).includes(sn) ? 'yes' : ''} | ${esc(who(sp.description))} |`);
  }
  out.push('');
}
const text = `${out.join('\n').trimEnd()}\n`;
const target = new URL('../docs/tools.md', import.meta.url);
if (process.argv.includes('--check')) {
  let current = ''; try { current = readFileSync(target, 'utf8'); } catch { /* missing */ }
  if (current !== text) { console.error('docs/tools.md is out of date — run: npm run docs:tools'); process.exit(1); }
  console.log('docs/tools.md is up to date');
} else { writeFileSync(target, text); console.log(`wrote docs/tools.md (${TOOLS.length} tools)`); }
